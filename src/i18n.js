      "voice.catalog.style.breezy": "лек",
      "voice.catalog.style.easyGoing": "непринуден",
      "voice.catalog.style.breathy": "с придихание",
      "voice.catalog.style.clear": "ясен",
      "voice.catalog.style.smooth": "плавен",
      "voice.catalog.style.gravelly": "дрезгав",
      "voice.catalog.style.soft": "мек",
      "voice.catalog.style.even": "равен",
      "voice.catalog.style.mature": "зрял",
